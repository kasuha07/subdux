package auth

import (
	"github.com/kasuha07/subdux/internal/model"
	"github.com/kasuha07/subdux/internal/service/serviceerr"
	"gorm.io/gorm"
)

// ErrCannotRemoveLastLoginMethod refuses to delete a credential that is the
// account's only remaining way to sign in.
var ErrCannotRemoveLastLoginMethod = serviceerr.New(
	serviceerr.KindInvalid,
	"cannot_remove_last_login_method",
	"cannot remove the last sign-in method; set a password or add a passkey first",
)

// ensureLoginMethodRemains reports ErrCannotRemoveLastLoginMethod when removing
// one OIDC connection or one passkey would leave the account with no usable
// sign-in method. A password counts unless it was generated by the server
// (OIDC auto-provisioning) and never known to the user. It must run inside the
// same transaction as the delete so concurrent deletions cannot both pass.
func ensureLoginMethodRemains(tx *gorm.DB, userID uint, removingOIDCConnectionID uint, removingPasskeyID uint) error {
	var user model.User
	if err := tx.Select("id", "password", "password_generated").First(&user, userID).Error; err != nil {
		return err
	}
	if user.Password != "" && !user.PasswordGenerated {
		return nil
	}

	var connections int64
	connectionQuery := tx.Model(&model.OIDCConnection{}).Where("user_id = ?", userID)
	if removingOIDCConnectionID != 0 {
		connectionQuery = connectionQuery.Where("id <> ?", removingOIDCConnectionID)
	}
	if err := connectionQuery.Count(&connections).Error; err != nil {
		return err
	}
	if connections > 0 {
		return nil
	}

	var passkeys int64
	passkeyQuery := tx.Model(&model.PasskeyCredential{}).Where("user_id = ?", userID)
	if removingPasskeyID != 0 {
		passkeyQuery = passkeyQuery.Where("id <> ?", removingPasskeyID)
	}
	if err := passkeyQuery.Count(&passkeys).Error; err != nil {
		return err
	}
	if passkeys > 0 {
		return nil
	}
	return ErrCannotRemoveLastLoginMethod
}
